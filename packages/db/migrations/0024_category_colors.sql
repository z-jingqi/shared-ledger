ALTER TABLE categories ADD COLUMN color TEXT NOT NULL DEFAULT '#FF681C';

UPDATE categories
SET color = CASE (sort_order % 8)
  WHEN 0 THEN '#64748B'
  WHEN 1 THEN '#FF681C'
  WHEN 2 THEN '#3B82F6'
  WHEN 3 THEN '#F59E0B'
  WHEN 4 THEN '#14B8A6'
  WHEN 5 THEN '#7C5CFC'
  WHEN 6 THEN '#EC4899'
  WHEN 7 THEN '#0EA5E9'
END
WHERE deleted_at IS NULL;
